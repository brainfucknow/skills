(ns acceptance.generator
  "Acceptance entrypoint generator (APS acceptance-generator.md): turns a
  parser JSON IR into a thin Babashka entry point plus metadata."
  (:require [babashka.fs :as fs]
            [cheshire.core :as json]
            [clojure.string :as str])
  (:import [java.security MessageDigest]))

(def usage "Usage: bb acceptance-generate <json-ir> <out-dir>")

(defn ir-stem [ir-path]
  (str/replace (str (fs/file-name ir-path)) #"\.json\z" ""))

(defn feature-path [ir-path]
  (str "features/" (ir-stem ir-path) ".feature"))

(defn metadata-name
  "The APS mapping: lowercase, each run of non-alphanumerics one hyphen,
  hyphens trimmed, then .json."
  [path]
  (-> (str/lower-case path)
      (str/replace #"[^a-z0-9]+" "-")
      (str/replace #"\A-+|-+\z" "")
      (str ".json")))

(defn entry-file-name [ir-path]
  (str (ir-stem ir-path) "_acceptance_test.clj"))

(defn- namespace-name [ir-path]
  (str "acceptance.generated." (-> (ir-stem ir-path) str/lower-case (str/replace #"[^a-z0-9]+" "-"))))

(defn entry-point
  "The generated test source. It holds the scenario structure only; example
  values come from whichever IR path the caller passes at run time."
  [ir-path ir]
  (str ";; Generated by bb acceptance-generate from " (feature-path ir-path) ". Do not edit.\n"
       "(ns " (namespace-name ir-path) "\n"
       "  (:require [acceptance.runtime :as runtime]\n"
       "            [acceptance.steps :as steps]))\n"
       "\n"
       "(def scenario-names\n"
       "  [" (str/join "\n   " (map #(pr-str (get % "name")) (get ir "scenarios"))) "])\n"
       "\n"
       "(defn run-tests\n"
       "  \"Runs every execution of the IR at ir-path, reporting each result.\"\n"
       "  [ir-path report]\n"
       "  (runtime/run-feature (runtime/load-ir ir-path) scenario-names steps/suite report))\n"))

(defn- sha256 [text]
  (let [digest (.digest (MessageDigest/getInstance "SHA-256") (.getBytes ^String text "UTF-8"))]
    (apply str (map #(format "%02x" (bit-and % 0xff)) digest))))

(defn implementation-hash
  "Hash over the generated files only, given as file name to content."
  [files]
  (str "sha256:" (sha256 (str/join (for [[file-name content] (sort files)]
                                     (str file-name "\n" (count content) "\n" content))))))

(defn generation
  "Every file to write, relative to out-dir, with its content."
  [ir-path out-dir ir]
  (let [entry-name (entry-file-name ir-path)
        entry (entry-point ir-path ir)
        feature (feature-path ir-path)]
    {entry-name entry
     (str "metadata/" (metadata-name feature))
     (str (json/generate-string
           (array-map :schema_version 1
                      :feature_path feature
                      :ir_path (str ir-path)
                      :implementation_hash (implementation-hash {entry-name entry})
                      :hash_scope "generated_files"
                      :generated_files [(str (fs/path out-dir entry-name))])
           {:pretty true})
          "\n")}))

(defn generate!
  "Writes the entry point and metadata for the IR into out-dir."
  [ir-path out-dir]
  (let [ir (json/parse-string (slurp (str ir-path)))]
    (doseq [[relative content] (generation ir-path out-dir ir)]
      (let [target (fs/path out-dir relative)]
        (fs/create-dirs (fs/parent target))
        (spit (fs/file target) content)))))

(defn generate-main [args]
  (if (not= 2 (count args))
    (do (binding [*out* *err*] (println usage))
        (System/exit 2))
    (System/exit
     (try
       (apply generate! args)
       0
       (catch Exception error
         (binding [*out* *err*]
           (println "acceptance-generate:" (ex-message error)))
         1)))))

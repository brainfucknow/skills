(ns compile-skills.compiler-spec
  (:require [compile-skills.compiler :as compiler]
            [compile-skills.fixtures :refer [skill]]
            [speclj.core :refer [describe it should= should-contain should-not-contain]]))

(defn user-invoked [skill-name]
  (assoc-in (skill skill-name "") [:files "SKILL.md"]
            (str "---\nname: " skill-name "\ndisable-model-invocation: true\n---\n\nBody\n")))

(defn headings [compiled]
  (re-seq #"(?m)^# Skill: .*$" compiled))

(describe "compile-skill"
  (it "writes frontmatter, marker, body and sorted file sections"
    (let [alpha (skill "alpha" "engineering" "# Alpha\n\nSee [notes](notes.md)."
                       {"notes.md" "# Notes\n\nBack to [the skill](./SKILL.md).\n"
                        "B.sh" "echo hi\n"})]
      (should= (str "---\nname: alpha\ndescription: D.\n---\n\n"
                    "<!-- Generated by bb compile-skills from skills/engineering/alpha/. Do not edit. -->\n\n"
                    "# Skill: alpha\n\n# Alpha\n\nSee [notes](#file-alphanotesmd).\n\n"
                    "## File: alpha/B.sh\n\n```sh\necho hi\n```\n\n"
                    "## File: alpha/notes.md\n\n# Notes\n\nBack to [the skill](#skill-alpha).\n")
               (compiler/compile-skill [alpha] alpha))))

  (it "turns CRLF line endings into LF"
    (let [alpha (skill "alpha" "engineering" "A" {"notes.md" "a\r\nb\r\n"})]
      (should-contain "\n\na\nb\n" (compiler/compile-skill [alpha] alpha))
      (should-not-contain "\r" (compiler/compile-skill [alpha] alpha))))

  (it "appends dependency sections without frontmatter"
    (let [root (skill "root" "Call the Skill tool with \"dep\".")
          dep (skill "dep" "productivity" "See [n](notes.md)." {"notes.md" "N\n"})
          compiled (compiler/compile-skill [root dep] root)]
      (should-contain "# Skill: dep\n\nSee [n](#file-depnotesmd).\n\n## File: dep/notes.md\n\nN\n" compiled)
      (should= 1 (count (re-seq #"name: " compiled))))))

(describe "dependency-names"
  (let [names #{"a" "b"}]
    (it "reads quoted and backticked names from the call to the sentence end"
      (should= ["a" "b"] (compiler/dependency-names names "call the Skill tool twice, for `a` and \"b\".")))
    (it "ignores names after the sentence ends or outside a call"
      (should= [] (compiler/dependency-names names "Call the Skill tool. Then read \"a\". Read \"b\".")))
    (it "ends the sentence at a line break"
      (should= [] (compiler/dependency-names names "Call the Skill tool\n\"a\"")))
    (it "ignores tokens that are not eligible names"
      (should= [] (compiler/dependency-names names "Call the Skill tool with \"c\".")))))

(describe "dependency-order"
  (it "is breadth first, each once, never the root"
    (let [root (skill "root" "Call the Skill tool twice, for \"a\" and \"b\".")
          a (skill "a" "Call the Skill tool twice, for \"c\" and \"b\".")
          b (skill "b" "Call the Skill tool with \"a\" and \"root\".")
          c (skill "c" "# C")]
      (should= ["a" "b" "c"] (map :name (compiler/dependency-order [root a b c] root)))))

  (it "skips user-invoked skills"
    (let [root (skill "root" "Call the Skill tool with \"u\".")]
      (should= [] (compiler/dependency-order [root (user-invoked "u")] root)))))

(describe "duplicate-names"
  (it "names every folder sharing a skill name"
    (should= [["alpha" ["skills/engineering/alpha" "skills/in-progress/alpha"]]]
             (compiler/duplicate-names [(skill "alpha" "in-progress" "" {})
                                        (skill "alpha" "")
                                        (skill "beta" "")]))))

(describe "compile-all"
  (it "maps each skill to compiled/<name>.md"
    (should= ["compiled/a.md" "compiled/b.md"]
             (keys (compiler/compile-all [(skill "b" "") (skill "a" "")])))))

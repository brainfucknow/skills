(ns compile-skills.compiler
  "Turns skills, read as plain data, into compiled skill files.

  A skill is {:name :bucket :files}, where :files maps each path relative to
  the skill folder to its text."
  (:require [clojure.string :as str]
            [compile-skills.markdown :as md]))

(def compiled-buckets ["engineering" "productivity" "in-progress"])

(def excluded-files #{"SKILL.md" "agents/openai.yaml"})

(defn skill-dir [{:keys [bucket name]}]
  (str "skills/" bucket "/" name))

(defn compiled-path [skill-name]
  (str "compiled/" skill-name ".md"))

(defn- skill-text [skill]
  (md/normalize-newlines (get-in skill [:files "SKILL.md"] "")))

(defn- frontmatter [skill]
  (:frontmatter (md/split-frontmatter (skill-text skill))))

(defn- body [skill]
  (:body (md/split-frontmatter (skill-text skill))))

(defn- inlined-paths [skill]
  (->> (keys (:files skill))
       (remove excluded-files)
       sort))

(defn duplicate-names
  "Each skill name held by more than one folder, with those folders."
  [skills]
  (->> (group-by :name skills)
       (filter #(< 1 (count (val %))))
       (sort-by key)
       (map (fn [[skill-name folders]] [skill-name (sort (map skill-dir folders))]))))

(defn- sentence-tails
  "Each span from a Skill tool call phrase to the end of its sentence."
  [text]
  (re-seq #"[Cc]all the Skill tool[^\n]*?(?:[.!?](?=\s|\z)|(?=\n)|\z)" text))

(defn- quoted-tokens [text]
  (map (fn [[_ quoted ticked]] (or quoted ticked))
       (re-seq #"\"([^\"\n]+)\"|`([^`\n]+)`" text)))

(defn dependency-names
  "Names of model-invoked skills named in Skill tool call sentences of the
  SKILL.md body, in order of appearance."
  [model-invoked-names body-text]
  (->> (sentence-tails body-text)
       (mapcat quoted-tokens)
       (filter model-invoked-names)
       distinct))

(defn- model-invoked-names [skills]
  (->> skills
       (remove #(md/user-invoked? (frontmatter %)))
       (map :name)
       set))

(defn- enqueue [state names]
  (reduce (fn [{:keys [seen] :as state} skill-name]
            (if (seen skill-name)
              state
              (-> state
                  (update :seen conj skill-name)
                  (update :queue conj skill-name))))
          state
          names))

(defn dependency-order
  "The skills inlined into the root, breadth first, each once, never the root."
  [skills root]
  (let [eligible (model-invoked-names skills)
        by-name (into {} (map (juxt :name identity)) skills)
        direct #(dependency-names eligible (body (by-name %)))]
    (loop [state (enqueue {:seen #{(:name root)}
                           :queue clojure.lang.PersistentQueue/EMPTY
                           :order []}
                          (direct (:name root)))]
      (if-let [skill-name (peek (:queue state))]
        (recur (-> state
                   (update :queue pop)
                   (update :order conj skill-name)
                   (enqueue (direct skill-name))))
        (map by-name (:order state))))))

(defn- join-blocks [blocks]
  (str/join "\n\n" (remove str/blank? blocks)))

(defn- link-context [skill relative-path]
  {:skill-name (:name skill)
   :files (set (inlined-paths skill))
   :folder (str/join "/" (butlast (str/split relative-path #"/")))})

(defn- file-content [skill relative-path]
  (let [text (md/trim-trailing-newlines
              (md/normalize-newlines (get-in skill [:files relative-path])))]
    (if (md/markdown-file? relative-path)
      (md/rewrite-links (link-context skill relative-path) text)
      (md/fence (md/extension relative-path) text))))

(defn- file-section [skill relative-path]
  (join-blocks [(md/file-heading (:name skill) relative-path)
                (file-content skill relative-path)]))

(defn skill-section [skill]
  (join-blocks (concat [(md/skill-heading (:name skill))
                        (md/rewrite-links (link-context skill "SKILL.md")
                                          (md/trim-blank-lines (body skill)))]
                       (map #(file-section skill %) (inlined-paths skill)))))

(defn- marker [skill]
  (str "<!-- Generated by bb compile-skills from " (skill-dir skill) "/. Do not edit. -->"))

(defn compile-skill
  "The compiled Markdown for root, given every compiled-bucket skill."
  [skills root]
  (str (join-blocks (concat [(frontmatter root) (marker root) (skill-section root)]
                            (map skill-section (dependency-order skills root))))
       "\n"))

(defn compile-all
  "Maps each compiled path to its content."
  [skills]
  (into (sorted-map)
        (map (fn [skill] [(compiled-path (:name skill)) (compile-skill skills skill)]))
        skills))
